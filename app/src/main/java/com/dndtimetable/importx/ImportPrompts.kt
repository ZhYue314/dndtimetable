package com.dndtimetable.importx

/**
 * 给用户复制到豆包等大模型的提示词，格式与「课表模板.xlsx」及导入器严格对应。
 * 采用「规则 + 转换示例」结构：示例覆盖大节换算、每节拆行、一格多课、跨三小节、午休节次五种常见坑。
 */
object ImportPrompts {

    private const val RULES = """你是一个课表格式转换助手。任务：把我提供的课表（图片、文字或文件）转成下面的标准格式，只输出数据行。

输出格式：每行一门课，7 列用竖线「|」分隔，顺序固定：
课程名称|星期|开始节数|结束节数|老师|地点|周数

输出顺序（必须遵守）：
- 按星期从小到大排：先输出全部周一的课，再输出周二、周三……直到周日
- 同一天内按开始节数从小到大排
- 例：先输出 周一第1-2节、周一第3-4节、周一第5-6节，再输出 周二第1-2节

规则：
1. 星期用数字 1-7（周一=1，周日=7）
2. 节次一律用小节编号 1-10，连续节次写「开始|结束」：第 1-2 节 → 1|2。同一门课连续多节只写一行，不要每节拆一行，也不要拆成 5-6、7-7 两行；跨三节写 5|7（例如某课在第 5-6 节和第 7 节都有 → 5|7）
3. 午休不算节次：如果原表把中午休息（约 12:10-14:00）也算成了两节，说明它的节次编号把午休算进去了。请跳过午休、按实际上课顺序重新编号，保证输出节次在 1-10 之间：原表第 7-8 节 → 输出 5-6；第 9-10 节 → 输出 7-8；第 11-12 节 → 输出 9-10
4. 原表只给大节编号时（第一大节=第 1-2 节）：第 N 大节 → 开始=2N-1、结束=2N（第二大节 → 3|4）；原表已经写了具体节次（如 [03-04节]、第 3-4 节）就直接照抄，不要再用大节换算
5. 周数只填周次：连续 1-16；单周 1-16单；双周 1-16双；多段用「、」连接，如 1-5、7-11单、12-16双；不连续如 2、5、8。不要带括号、[xx-xx节]、教室等多余文字
6. 老师、地点没有就留空，但竖线必须保留
7. 原表是文件（.xls/.xlsx/.csv）时必须直接读取文件内容，不要凭截图或印象推测
8. 完整扫描（最容易漏的地方）：课表常按「上午 / 下午 / 晚上」分成上下多块，或左右分栏。必须逐块、逐行、逐格读完，上午、下午、晚上一个都不能少；表格下半部分和右侧（周六/周日列）尤其容易漏，不要把下午/晚上的课程行当成表头或说明跳过
9. 一门都不能漏（含 MOOC、网课、实践课）；同一个格子里有多门课就写多行
10. 课程名、老师、地点等文字以原表为准，不要按形近字猜测（如「冉冰心」不要写成「再冰心」），拿不准的宁可留空
11. 无法确定星期或节次的课程不要输出
12. 输出前逐格核对：按「星期 × 节次」把原表每一个有课的格子对照输出，确保每格都有一行；重点复查下午、晚上、周末和表格最右侧

示例 1（大节表格：下午的课也要读，先周一后周二、同天按节次）：
原表：周一第一大节 大学物理 张三 302 1-16周；周一第二大节 计算机原理 李四 309 1-16周；周一第三大节 形势与政策 陈婷婷 行思楼-109 1-4周；周二第一大节 高等数学 王五 101 1-16周
大学物理|1|1|2|张三|302|1-16
计算机原理|1|3|4|李四|309|1-16
形势与政策|1|5|6|陈婷婷|行思楼-109|1-4
高等数学|2|1|2|王五|101|1-16

示例 2（同一门课被按节拆成多行 → 合并）：原表 周二第1节 线性代数 王五 A203 1-16周；周二第2节 线性代数 王五 A203 1-16周
线性代数|2|1|2|王五|A203|1-16

示例 3（一个格子里多门课）：原表 周四第三大节 同时有 体育（赵六）和 音乐鉴赏（钱七），均 1-16 周
体育|4|5|6|赵六||1-16
音乐鉴赏|4|5|6|钱七||1-16

示例 4（跨三小节的课，只写一行）：原表 周二第 5-6 节 微生物学实验 李向阳；周二第 7 节 微生物学实验 李向阳（同一门课占 5、6、7 节）
微生物学实验|2|5|7|李向阳||1-16

示例 5（原表含午休节次，输出要前移）：原表 周四第 7-8 节 电工电子技术 肖涛 1-10周；周四第 11-12 节 晚自习课 王五 1-8周（原表 12 节含午休 5-6 节）
电工电子技术|4|5|6|肖涛||1-10
晚自习课|4|9|10|王五||1-8

上面的示例只说明格式与排序，不要照抄；只输出我课表的真实课程。"""

    /** 文字版：大模型输出纯文本，用户复制结果回 App 粘贴导入。 */
    val TEXT: String = RULES + "\n\n请只输出数据行（纯文本），不要输出表格、代码块或任何解释。"

    /** 模板版：模板自带列和示例行，提示词说明任务与几个关键换算。 */
    val EXCEL_TEMPLATE: String =
        "将我提供的图片或 Excel 文件中的课程转为标准模板的格式：" +
            "我会同时提供标准模板文件「课表模板.xlsx」，请严格按它的列和表头填写，输出填好的 .xlsx 文件；" +
            "模板里的示例行只是格式说明，请全部替换成我的真实课程；" +
            "原表按大节编号时换算成小节（第二大节=3-4节，不要把大节号直接填进节次列）；" +
            "原表把午休（约 12:10-14:00）也算成节次时跳过午休重新编号（原表 7-8 → 5-6、9-10 → 7-8、11-12 → 9-10）；" +
            "同一门课跨多节只写一行（占 5、6、7 节 → 5-7）；" +
            "按星期、节次从小到大排序（先周一再周二）；" +
            "上午/下午/晚上所有区块逐格读取、逐格核对，所有课程（含 MOOC/网课）一门都不能漏。"

    /** 直接生成版：不发模板，让大模型直接生成标准 .xlsx。 */
    val EXCEL: String = RULES + "\n\n请直接生成一个 .xlsx 文件（不要输出 CSV 或 Markdown 表格）：" +
        "第一个工作表的第一行是表头，A-G 列依次为「课程名称、星期、开始节数、结束节数、老师、地点、周数」，数据从第二行开始；" +
        "星期、开始节数、结束节数三列必须是纯数字，不要带「周」「第」「节」等文字；除表头和数据行外不要加其他内容。"
}
